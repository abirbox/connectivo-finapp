const COOKIE_NAME = 'cf_session';
const SESSION_TTL_MS = 8 * 60 * 60 * 1000; // 8 hours

// ---- small byte/hex/base64url helpers (Web Crypto works in bytes) ----
function hexToBytes(hex) {
  const arr = new Uint8Array(hex.length / 2);
  for (let i = 0; i < arr.length; i++) arr[i] = parseInt(hex.substr(i * 2, 2), 16);
  return arr;
}
function b64url(bytes) {
  let bin = '';
  bytes.forEach((b) => { bin += String.fromCharCode(b); });
  return btoa(bin).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}
function fromB64url(str) {
  const bin = atob(str.replace(/-/g, '+').replace(/_/g, '/'));
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}
function constantTimeEqualBytes(a, b) {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a[i] ^ b[i];
  return diff === 0;
}
function constantTimeEqualStr(a, b) {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

/** Password hashing: PBKDF2-HMAC-SHA256 via the standard Web Crypto API —
 * the closest native equivalent to Node's scrypt that Workers actually
 * support without extra dependencies. Stored format is
 * "<iterations>:<saltHex>:<hashHex>", generated by scripts/hash-password.cjs,
 * so the iteration count can change later without breaking old hashes. */
const HASH_ITERATIONS = 100000; // Cloudflare Workers' crypto.subtle hard cap for PBKDF2 — exceeding it throws NotSupportedError

/** Verifies a plaintext password against a stored "iterations:salt:hash"
 * string (as produced by hashPassword() below, or scripts/hash-password.cjs).
 * Exported as verifyPasswordHash for use by lib/accounts.js. */
export async function verifyPasswordHash(password, stored) {
  if (!stored || stored.split(':').length !== 3) return false;
  const [iterStr, saltHex, hashHex] = stored.split(':');
  const iterations = parseInt(iterStr, 10);
  // This bound both documents the platform limit and fails cleanly (as
  // "wrong credentials") rather than throwing, if a hash is ever produced
  // with too high a count by mistake.
  if (!iterations || iterations < 1000 || iterations > 100000) return false;
  const salt = hexToBytes(saltHex);
  const expected = hexToBytes(hashHex);
  const keyMaterial = await crypto.subtle.importKey('raw', new TextEncoder().encode(password || ''), { name: 'PBKDF2' }, false, ['deriveBits']);
  const derivedBits = await crypto.subtle.deriveBits({ name: 'PBKDF2', salt, iterations, hash: 'SHA-256' }, keyMaterial, expected.length * 8);
  return constantTimeEqualBytes(new Uint8Array(derivedBits), expected);
}

/** Generates a brand-new "iterations:salt:hash" string for a plaintext
 * password — the in-app equivalent of scripts/hash-password.cjs, used by
 * the profile-update endpoint so people can change their own password
 * without ever touching a terminal. Uses the same PBKDF2 scheme and
 * iteration count as verification, so it's guaranteed to verify correctly. */
export async function hashPassword(password) {
  const saltBytes = crypto.getRandomValues(new Uint8Array(16));
  const saltHex = Array.from(saltBytes).map((b) => b.toString(16).padStart(2, '0')).join('');
  const keyMaterial = await crypto.subtle.importKey('raw', new TextEncoder().encode(password), { name: 'PBKDF2' }, false, ['deriveBits']);
  const derivedBits = await crypto.subtle.deriveBits({ name: 'PBKDF2', salt: saltBytes, iterations: HASH_ITERATIONS, hash: 'SHA-256' }, keyMaterial, 256);
  const hashHex = Array.from(new Uint8Array(derivedBits)).map((b) => b.toString(16).padStart(2, '0')).join('');
  return `${HASH_ITERATIONS}:${saltHex}:${hashHex}`;
}

/** Session tokens: base64url JSON payload + HMAC-SHA256 signature, keyed by
 * the SESSION_SECRET binding (set in the Cloudflare dashboard — any long
 * random string, e.g. from `openssl rand -hex 32`). */
async function hmacSign(payloadB64, secret) {
  const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(secret), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  const sig = await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(payloadB64));
  return b64url(new Uint8Array(sig));
}
export async function makeSessionToken(acct, env) {
  const secret = env.SESSION_SECRET;
  if (!secret) throw new Error("SESSION_SECRET is not configured in this project's environment variables.");
  const payloadObj = { uid: acct.uid, role: acct.role, name: acct.name, iat: Date.now(), exp: Date.now() + SESSION_TTL_MS };
  const payload = b64url(new TextEncoder().encode(JSON.stringify(payloadObj)));
  const sig = await hmacSign(payload, secret);
  return `${payload}.${sig}`;
}
export async function verifySessionToken(token, env) {
  try {
    const secret = env.SESSION_SECRET;
    if (!secret || !token) return null;
    const [payload, sig] = token.split('.');
    if (!payload || !sig) return null;
    const expectedSig = await hmacSign(payload, secret);
    if (!constantTimeEqualStr(sig, expectedSig)) return null;
    const data = JSON.parse(new TextDecoder().decode(fromB64url(payload)));
    if (data.exp && Date.now() > data.exp) return null;
    return data;
  } catch (e) { return null; }
}

export function cookieFor(token) {
  const maxAge = Math.floor(SESSION_TTL_MS / 1000);
  return `${COOKIE_NAME}=${token}; Path=/; HttpOnly; Secure; SameSite=Strict; Max-Age=${maxAge}`;
}
export function clearCookie() {
  return `${COOKIE_NAME}=; Path=/; HttpOnly; Secure; SameSite=Strict; Max-Age=0`;
}
export async function getSessionFromRequest(request, env) {
  const header = request.headers.get('Cookie') || '';
  const match = header.match(new RegExp(`${COOKIE_NAME}=([^;]+)`));
  if (!match) return null;
  return verifySessionToken(decodeURIComponent(match[1]), env);
}

export function json(statusCode, obj, extraHeaders) {
  return new Response(JSON.stringify(obj), {
    status: statusCode,
    headers: { 'Content-Type': 'application/json', ...(extraHeaders || {}) },
  });
}
